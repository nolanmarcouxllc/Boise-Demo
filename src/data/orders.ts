type Seed = {
  id: string
  customerId: string
  locationId: string
  status: OrderStatus
  createdAt: string
  requestedDate?: string
  window: [string, string]
  lines: Array<[string, number]>
  valueUsd: number
  routeId: string | null
  fleetEligibility: Order['fleetEligibility']
  writtenBy: string
  dataFlags?: string[]
  notes: string
  lastChangeAt?: string
  lastChangeNote?: string
}

function buildLines(pairs: Array<[string, number]>): OrderLine[] {
  return pairs.map(([sku, qty]) => {
    const p = productBySku.get(sku)
    if (!p) throw new Error(`Unknown demonstration SKU: ${sku}`)
    return { sku, qty, unit: p.unit, weightLbs: Math.round(p.lbsPerUnit * qty), lengthFt: p.lengthFt }
  })
}

function build(seed: Seed): Order {
  const lines = buildLines(seed.lines)
  return {
    id: seed.id,
    customerId: seed.customerId,
    locationId: seed.locationId,
    status: seed.status,
    createdAt: seed.createdAt,
    requestedDate: seed.requestedDate ?? TODAY,
    window: seed.window,
    lines,
    totalWeightLbs: lines.reduce((sum, l) => sum + l.weightLbs, 0),
    maxLengthFt: lines.reduce((max, l) => Math.max(max, l.lengthFt), 0),
    valueUsd: seed.valueUsd,
    routeId: seed.routeId,
    fleetEligibility: seed.fleetEligibility,
    writtenBy: seed.writtenBy,
    dataFlags: seed.dataFlags ?? [],
    notes: seed.notes,
    lastChangeAt: seed.lastChangeAt,
    lastChangeNote: seed.lastChangeNote,
  }
}

