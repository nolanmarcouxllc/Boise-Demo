function stopWeight(orderIds: string[]): number {
  return orderIds.reduce((sum, id) => sum + (orderById.get(id)?.totalWeightLbs ?? 0), 0)
}

export const routes: Route[] = seeds.map((seed) => {
  const stops: RouteStop[] = seed.stops.map((s) => ({ ...s, weightLbs: stopWeight(s.orderIds) }))
  const truck = seed.truckId ? trucks.find((t) => t.id === seed.truckId) : undefined
  return {
    ...seed,
    date: TODAY,
    stops,
    weightLbs: stops.reduce((sum, s) => sum + s.weightLbs, 0),
    capacityLbs: truck?.capacityLbs ?? seed.capacityLbs ?? 46000,
  }
})

export const routeById = new Map(routes.map((r) => [r.id, r]))

export function utilization(route: Route): number {
  return Math.round((route.weightLbs / route.capacityLbs) * 100)
}

export function routeHealthLabel(h: Health): string {
  return h === 'ok' ? 'On plan' : h === 'attention' ? 'Needs attention' : 'At risk'
}
